"""The GitHub export selection stays public-clean.

scripts/export-manifest is the allowlist (tracked files minus internal/);
scripts/check-public-tree scans exactly those bytes. A planted private
marker must fail the scan, and the current tree must pass it.
"""
import json
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EXPORT_MANIFEST = ROOT / "scripts" / "export-manifest"
CHECK_PUBLIC_TREE = ROOT / "scripts" / "check-public-tree"


def run(*args, cwd=ROOT):
    return subprocess.run([sys.executable, *args], cwd=cwd,
                          capture_output=True, text=True)


class PublicTreeTests(unittest.TestCase):
    def test_manifest_excludes_internal(self):
        result = run(EXPORT_MANIFEST)
        self.assertEqual(result.returncode, 0, result.stderr)
        paths = result.stdout.splitlines()
        self.assertTrue(paths)
        self.assertIn("README.md", paths)
        self.assertIn("scripts/check-public-tree", paths)
        self.assertIn("schema/conventions-events.json", paths)
        self.assertFalse([p for p in paths if p.startswith("internal/")],
                         "internal/ guidance must not publish")

    def test_clean_tree_passes(self):
        result = run(CHECK_PUBLIC_TREE)
        self.assertEqual(result.returncode, 0,
                         f"public tree leaks: {result.stdout}")

    def test_conventions_copies_match_and_ship(self):
        # schema/conventions-events.json is the single source: the
        # Python package copy and the npm copy (generated by
        # typescript/build-docs.mjs) must carry the same bytes.
        source = (ROOT / "schema" / "conventions-events.json").read_bytes()
        packaged = (ROOT / "flattrace" / "schema"
                    / "conventions-events.json").read_bytes()
        self.assertEqual(packaged, source)
        contract = json.loads(source.decode("utf-8"))
        self.assertEqual(contract["tool"], "flattrace-conventions")
        package = json.loads((ROOT / "typescript" / "package.json")
                             .read_text())
        self.assertIn("schema/conventions-events.json", package["files"])
        build_docs = (ROOT / "typescript" / "build-docs.mjs").read_text()
        self.assertIn("schema/conventions-events.json", build_docs)

    def test_every_planted_rule_and_case_fails(self):
        # Split literals keep these policy tests public-scannable themselves.
        terms = ["zam" "il", "mario" ".garden", "kyra" "-server",
                 "for" "gejo", "/data" "pool", "rust" "bat", ":222" "/",
                 "shared" "brain", "git.mario" ".garden"]
        prefixes = ["go" "al.", "sub" "agents.", "mon" "itor."]
        with tempfile.TemporaryDirectory() as directory:
            planted = Path(directory) / "note.md"
            for term in terms + prefixes:
                for case in (str.lower, str.upper):
                    samples = [case(term)]
                    if term in prefixes:
                        samples += [json.dumps({"event": case(term + "start")}),
                                    case(term + "start"),
                                    json.dumps({"event": case(term)})]
                    for sample in samples:
                        with self.subTest(sample=sample):
                            planted.write_text(sample + "\n")
                            result = run(CHECK_PUBLIC_TREE, "--root", directory, "note.md")
                            self.assertEqual(result.returncode, 1, result.stdout)
                            self.assertIn("note.md", result.stdout)
            planted.write_text("We reached the go" "al.\nWatch the mon" "itor.\n")
            result = run(CHECK_PUBLIC_TREE, "--root", directory, "note.md")
            self.assertEqual(result.returncode, 0, result.stdout)


if __name__ == "__main__":
    unittest.main()
